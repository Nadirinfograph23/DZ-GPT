// فهرس: السنة → الحكومات النشطة في تلك السنة
const YEAR_INDEX = new Map()
for (const gov of HISTORICAL_GOVERNMENTS) {
  for (let y = gov.period.from; y <= Math.min(gov.period.to, 2030); y++) {
    if (!YEAR_INDEX.has(y)) YEAR_INDEX.set(y, [])
    YEAR_INDEX.get(y).push(gov)
  }
}

// فهرس: الوزارة → قائمة الوزراء عبر التاريخ
const MINISTRY_INDEX = new Map()
for (const gov of HISTORICAL_GOVERNMENTS) {
  for (const m of gov.ministers) {
    const key = normalizeMin(m.role)
    if (!MINISTRY_INDEX.has(key)) MINISTRY_INDEX.set(key, [])
    MINISTRY_INDEX.get(key).push({ ...m, government: gov })
  }
}

function normalizeMin(str = '') {
  return str.replace(/^وزير\s+(ال)?/, '').replace(/\s+/g, ' ').trim().toLowerCase()
    .replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
}

