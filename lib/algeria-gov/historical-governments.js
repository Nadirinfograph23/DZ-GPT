/**
 * البحث في الحكومات حسب السنة
 */
export function findGovByYear(year) {
  const y = parseInt(year, 10)
  if (isNaN(y)) return []
  return YEAR_INDEX.get(y) || []
}

/**
 * البحث عن وزير حسب الحقيبة والسنة (اختياريان)
 */
export function findMinisterByPortfolio(portfolioQuery, year = null) {
  const qNorm = normalizeMin(portfolioQuery)
  const results = []

  for (const [key, entries] of MINISTRY_INDEX) {
    // مطابقة جزئية للحقيبة
    if (key.includes(qNorm) || qNorm.includes(key) || qNorm.split(' ').some(w => w.length > 2 && key.includes(w))) {
      for (const entry of entries) {
        if (year) {
          const y = parseInt(year, 10)
          const g = entry.government
          if (y >= g.period.from && y <= g.period.to) {
            results.push(entry)
          }
        } else {
          results.push(entry)
        }
      }
    }
  }

  // إزالة التكرار بالاسم
  const seen = new Set()
  return results.filter(r => {
    const k = `${r.name}-${r.government?.id}`
    if (seen.has(k)) return false
    seen.add(k)
    return true
  })
}

/**
 * البحث عن حكومات رئيس معين
 */
export function findGovsByPresident(presidentName) {
  const q = presidentName.replace(/\s+/g, ' ').trim().toLowerCase()
    .replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
  return HISTORICAL_GOVERNMENTS.filter(g => {
    const pNorm = g.president.toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
    const pmNorm = g.pm.toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
    return pNorm.includes(q) || pmNorm.includes(q) || q.includes(pNorm.split(' ')[0])
  })
}

