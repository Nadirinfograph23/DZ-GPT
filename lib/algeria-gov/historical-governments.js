const YEAR_RE = /\b(19[6-9]\d|20[0-2]\d)\b/
const PORTFOLIO_KEYWORDS = [
  'خارجية', 'داخلية', 'دفاع', 'مالية', 'طاقة', 'تربية', 'تعليم', 'صحة',
  'صناعة', 'فلاحة', 'إسكان', 'سكن', 'شباب', 'رياضة', 'اتصال', 'ثقافة',
  'عدل', 'نقل', 'سياحة', 'دين', 'شؤون دينية', 'بيئة', 'أشغال', 'تجارة',
  'عمل', 'تكوين', 'مهني', 'موارد مائية', 'بريد', 'مواصلات',
]

export function parseHistoricalGovQuery(message) {
  if (!message) return null
  const msg = message

  // استخراج السنة
  const yearMatch = msg.match(YEAR_RE)
  const year = yearMatch ? parseInt(yearMatch[1], 10) : null

  // استخراج الحقيبة
  const portfolioFound = PORTFOLIO_KEYWORDS.find(k => msg.includes(k))

  // استخراج اسم الرئيس/الوزير الأول
  const presidentNames = [
    'بن بلة', 'بومدين', 'بن جديد', 'زروال', 'بوتفليقة',
    'تبون', 'العرباوي', 'سلال', 'بن عبد الرحمن', 'جراد',
    'أويحيى', 'مرباح', 'براهيمي', 'حمروش', 'غزالي', 'مالك رضا',
    'بدوي', 'بن فليس', 'بن بيتور', 'سيفي غريب', 'غريب',
  ]
  const presidentFound = presidentNames.find(p => {
    const pNorm = p.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
    const msgNorm = msg.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
    return msgNorm.includes(pNorm)
  })

  if (!year && !portfolioFound && !presidentFound) return null

  return { year, portfolio: portfolioFound || null, president: presidentFound || null }
}

export function isHistoricalGovQuery(message) {
  if (!message) return false
  return !!(
    // حكومة + رئيس
    /حكومة\s+(?:بوتفليقة|بن\s*بلة|بومدين|زروال|تبون|سلال|أويحيى|مرباح|براهيمي|حمروش|غزالي|بن\s+جديد|بدوي|العرباوي|بن\s+عبد\s+الرحمن|جراد|سيفي\s+غريب|غريب)/i.test(message) ||
    // وزير + حقيبة + سنة
    (/وزير\s+(?:ال)?(?:خارجية|داخلية|مالية|تربية|تعليم|صحة|صناعة|فلاحة|طاقة|عدل|إسكان|ثقافة|رياضة|اتصال)/i.test(message) && YEAR_RE.test(message)) ||
    // من كان وزير X سنة Y
    /(?:من\s+كان|من\s+هو|شكون\s+كان)\s+وزير/i.test(message) ||
    // وزراء فترة / عهد / زمن
    /وزراء\s+(?:فترة|عهد|زمن|حكومة|عصر)\s+/i.test(message) ||
    // وزير التربية / الصحة / ... سنة YYYY
    (PORTFOLIO_KEYWORDS.some(k => message.includes(k)) && YEAR_RE.test(message)) ||
    // وزراء الخارجية / الداخلية / المالية في تاريخ الجزائر
    /وزراء\s+(?:ال)?(?:خارجية|داخلية|مالية|تربية|تعليم|صحة|صناعة|فلاحة|طاقة|عدل|إسكان|ثقافة|رياضة|اتصال)(?:\s+في\s+تاريخ|\s+الجزائر)?/i.test(message) ||
    // تاريخ الحكومات / كل الحكومات الجزائرية
    /(?:تاريخ|قائمة|كل|جميع)\s+(?:ال)?حكومات\s+(?:الجزائر|الجزائرية)/i.test(message) ||
    // الوزراء الأوائل في تاريخ الجزائر
    /وزير\s+أول\s+في\s+تاريخ|رؤساء\s+الحكومات\s+الجزائرية/i.test(message)
  )
}

