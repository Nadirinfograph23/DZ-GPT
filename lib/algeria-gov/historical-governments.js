// § 5 — بناء سياق النص للـ prompt
// ══════════════════════════════════════════════════════════════════════════════

export function buildHistoricalGovContext(query) {
  const parsed = parseHistoricalGovQuery(query)
  if (!parsed) return ''

  const { year, portfolio, president } = parsed
  const lines = ['## 🏛️ الحكومات الجزائرية — قاعدة بيانات تاريخية']

  // ── حالة 1: البحث بالرئيس ─────────────────────────────────────────────────
  if (president && !year && !portfolio) {
    const govs = findGovsByPresident(president)
    if (!govs.length) {
      lines.push(`> لا توجد بيانات عن حكومة "${president}" في قاعدة البيانات.`)
      return lines.join('\n')
    }
    for (const gov of govs) {
      lines.push(`### حكومة ${gov.president} (${gov.periodLabel})`)
      lines.push(`> 🗓️ الوزير الأول: **${gov.pm}**`)
      if (gov.note) lines.push(`> 📝 ${gov.note}`)
      lines.push('')
      lines.push('| المنصب | الوزير |')
      lines.push('|--------|--------|')
      for (const m of gov.ministers) {
        lines.push(`| ${m.role}${m.years ? ` (${m.years})` : ''} | **${m.name}** |`)
      }
      lines.push('')
    }
    return lines.join('\n')
  }

  // ── حالة 2: البحث بالسنة ─────────────────────────────────────────────────
  if (year && !portfolio) {
    const govs = findGovByYear(year)
    if (!govs.length) {
      lines.push(`> لا توجد بيانات لسنة ${year} في قاعدة البيانات.`)
      return lines.join('\n')
    }
    lines.push(`> 📅 السنة المطلوبة: **${year}**`)
    lines.push('')
    for (const gov of govs) {
      lines.push(`### حكومة ${gov.president} — الوزير الأول: ${gov.pm}`)
      lines.push(`> 🗓️ الفترة: **${gov.periodLabel}**`)
      if (gov.note) lines.push(`> 📝 ${gov.note}`)
      lines.push('')
      lines.push('| المنصب | الوزير |')
      lines.push('|--------|--------|')
      for (const m of gov.ministers) {
        lines.push(`| ${m.role}${m.years ? ` (${m.years})` : ''} | **${m.name}** |`)
      }
      lines.push('')
    }
    return lines.join('\n')
  }

  // ── حالة 3: البحث بالحقيبة + سنة اختيارية ────────────────────────────────
  if (portfolio) {
    const ministers = findMinisterByPortfolio(portfolio, year)
    if (!ministers.length) {
      lines.push(`> لا توجد بيانات عن وزير ${portfolio}${year ? ` سنة ${year}` : ''}.`)
      return lines.join('\n')
    }
    const title = year
      ? `وزير **${portfolio}** سنة **${year}**`
      : `وزراء **${portfolio}** عبر التاريخ`
    lines.push(`### ${title}`)
    lines.push('')
    lines.push('| الحكومة | الفترة | الوزير |')
    lines.push('|---------|--------|--------|')
    for (const m of ministers) {
      const g = m.government
      lines.push(`| حكومة ${g?.president || '—'} | ${g?.periodLabel || '—'} | **${m.name}** |`)
    }
    lines.push('')
    if (year) {
      // أضف سياقاً عن الحكومة كاملاً في تلك السنة
      const govs = findGovByYear(year)
      if (govs.length) {
        lines.push(`> 📋 الحكومة الكاملة لسنة ${year}: **حكومة ${govs[0].president}** (${govs[0].periodLabel}) — الوزير الأول: ${govs[0].pm}`)
      }
    }
    return lines.join('\n')
  }

  return lines.join('\n')
}
