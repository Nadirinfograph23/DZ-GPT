/**
 * isAgentSelfQuery(query) — هل السؤال عن هوية الوكيل أو خدماته؟
 * @param {string} query
 * @returns {boolean}
 */
export function isAgentSelfQuery(query = '') {
  if (!query) return false
  const q = query.trim().toLowerCase()
    .replace(/[؟?!.،,]/g, '')
    .replace(/\s+/g, ' ')
  return SELF_QUERY_PATTERNS.some(p => q.includes(p.toLowerCase()))
}

/**
 * getAgentIdentityBlock(query) — يُعيد كتلة الهوية المناسبة للـ system prompt
 *
 * - إذا كان السؤال عن الهوية/الخدمات → كتلة كاملة (للرد المباشر)
 * - دائماً → رأس مختصر (لإعلام النموذج بهويته)
 *
 * @param {string} query
 * @returns {{ short: string, full: string|null, isSelfQuery: boolean }}
 */
export function getAgentIdentityBlock(query = '') {
  const isSelfQuery = isAgentSelfQuery(query)
  return {
    short: DZ_AGENT_IDENTITY_SHORT,
    full: isSelfQuery ? DZ_AGENT_FULL_IDENTITY : null,
    isSelfQuery,
  }
}
