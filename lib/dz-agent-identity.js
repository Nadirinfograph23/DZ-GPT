/**
 * isAgentSelfQuery(query) — هل السؤال عن هوية الوكيل أو خدماته؟
 * @param {string} query
 * @returns {boolean}
 */
export function isAgentSelfQuery(query = '') {
  if (!query) return false
  const q = query.trim().toLowerCase()
    .replace(/[؟?!.،,]/g, '')
    .replace(/\s+/g, ' ')
  return SELF_QUERY_PATTERNS.some(p => q.includes(p.toLowerCase()))
}

