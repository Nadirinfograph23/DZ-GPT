/**
 * matchCapabilityQuery(query) — هل السؤال عن خدمة بعينها؟
 * يُعيد كائن الخدمة أو null
 */
export function matchCapabilityQuery(query = '') {
  if (!query) return null
  const q = query.toLowerCase().replace(/[؟?!.،,]/g, '').replace(/\s+/g, ' ')
  for (const svc of DZ_AGENT_SERVICES_KB) {
    if (svc.keywords.some(kw => q.includes(kw.toLowerCase()))) return svc
  }
  return null
}

/**
 * getCapabilityResponse(query) — يُعيد رد جاهز عن الخدمة المطلوبة أو null
 */
export function getCapabilityResponse(query = '') {
  const svc = matchCapabilityQuery(query)
  return svc ? svc.response : null
}

