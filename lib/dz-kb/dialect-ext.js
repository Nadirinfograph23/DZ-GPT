export function isDialectQuery(msg) {
  return /دارجة|لهجة جزائرية|عامية جزائرية|ماذا تعني.*بالدارجة|قاموس.*جزائري|ترجمة.*دارجة|كلمة جزائرية|أمازيغية|فرانكو عربي|كيف نقول.*جزائر|كلمة.*وهران|كلمة.*قسنطينة|كلمة.*قبايل/i.test(msg)
}

export function getDialectContext(msg) {
  const clean = msg.toLowerCase()
  const sections = []

  for (const [region, data] of Object.entries(DZ_DIALECT_REGIONS)) {
    if (clean.includes(region.split(' ')[0].toLowerCase())) {
      const exprs = Object.entries(data.expressions || data.amaz_words || data.french_arabic || {}).slice(0,8)
      sections.push(`**${region}**:\n${exprs.map(([k,v]) => `• "${k}" = ${v}`).join('\n')}`)
      break
    }
  }

  if (sections.length === 0) {
    // تعابير شائعة عامة
    const common = Object.entries(DZ_COMMON_PHRASES.everyday).slice(0,10)
    sections.push(`**تعابير الدارجة الجزائرية الشائعة**:\n${common.map(([k,v]) => `• "${k}" = ${v}`).join('\n')}`)
  }

  return `[DZ_DIALECT]\n${sections.join('\n\n')}\n[/DZ_DIALECT]`
}
