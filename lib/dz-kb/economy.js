export function isEconomyQuery(msg) {
  return /اقتصاد الجزائر|استثمار.*جزائر|شركة.*جزائر|سجل تجاري|CNRC|AAPI|ALNAFT|ناتج محلي|بطالة|دينار جزائري|سعر الصرف|محروقات.*اقتصاد|سوناطراك|فلاحة.*جزائر|صناعة.*جزائر|أعمال.*جزائر|business.*algérie|استثمار.*جزائر|إنشاء شركة/i.test(msg)
}

export function getEconomyContext(msg) {
  const sections = []
  if (/محروقات|نفط|غاز|سوناطراك/i.test(msg)) {
    const s = DZ_ECONOMY.sectors.hydrocarbons
    sections.push(`**قطاع المحروقات**: ${s.share}\nأبرز الشركات: ${s.companies.join('، ')}\nالحقول الرئيسية: ${s.key_fields.join('، ')}`)
  }
  if (/شركة|CNRC|سجل تجاري|تأسيس/i.test(msg)) {
    const p = DZ_ECONOMY.procedures.create_company
    sections.push(`**إنشاء شركة**:\n${p.steps.join('\n')}`)
  }
  if (/استثمار|AAPI/i.test(msg)) {
    const p = DZ_ECONOMY.procedures.investment
    sections.push(`**الاستثمار في الجزائر** — ${p.agency}\nالمزايا: ${p.advantages.join(' · ')}`)
  }
  if (sections.length === 0) {
    const o = DZ_ECONOMY.overview
    sections.push(`**الاقتصاد الجزائري — نظرة عامة**:\n• الناتج المحلي: ${o.gdp}\n• القطاع الرئيسي: ${o.main_sector}\n• احتياطي الصرف: ${o.reserves}\n• العملة: ${o.currency}`)
    sections.push(`المحاور الاقتصادية:\n${DZ_ECONOMY.economic_strengths.slice(0,4).map(s => `✅ ${s}`).join('\n')}\nالتحديات:\n${DZ_ECONOMY.economic_challenges.slice(0,3).map(c => `⚠️ ${c}`).join('\n')}`)
  }
  return `[DZ_ECONOMY]\n${sections.join('\n\n')}\n[/DZ_ECONOMY]`
}
