export function isFamousQuery(msg) {
  return /مشاهير الجزائر|جزائريين مشهورين|أبرز شخصيات جزائرية|علماء جزائر|فنانون جزائر|رياضيون جزائر|سياسيون جزائر|من هو أشهر|أشهر جزائري/i.test(msg) ||
    DZ_FAMOUS.some(p => msg.includes(p.name.split(' ')[0]) || (p.name.split(' ')[1] && msg.includes(p.name.split(' ')[1])))
}

export function getFamousContext(msg) {
  const clean = msg.toLowerCase()
  // ابحث عن الشخص بالاسم
  const byName = DZ_FAMOUS.filter(p =>
    p.name.toLowerCase().split(' ').some(w => w.length > 3 && clean.includes(w))
  )
  if (byName.length > 0) {
    return `[DZ_FAMOUS_ALGERIANS]\n${byName.slice(0,3).map(p =>
      `**${p.name}** (${p.field} — ${p.from})\n${p.bio}`
    ).join('\n\n')}\n[/DZ_FAMOUS_ALGERIANS]`
  }
  // حسب المجال
  const fieldMap = {
    'رياضة|كرة|لاعب': 'كرة قدم',
    'موسيقى|مطرب|مغني|راي': 'موسيقى',
    'أدب|روايات|كاتب': 'أدب',
    'تاريخ|ثورة|مقاومة': 'سياسة وثورة',
    'علم|فلسفة|فيلسوف': 'فلسفة',
    'سياسة|رئيس|وزير': 'سياسة',
  }
  for (const [pat, field] of Object.entries(fieldMap)) {
    if (new RegExp(pat, 'i').test(msg)) {
      const byField = DZ_FAMOUS.filter(p => p.field.includes(field.split(' ')[0]))
      if (byField.length > 0) {
        return `[DZ_FAMOUS_ALGERIANS — ${field}]\n${byField.slice(0,5).map(p => `• **${p.name}** (${p.from}): ${p.bio.slice(0,100)}...`).join('\n')}\n[/DZ_FAMOUS_ALGERIANS]`
      }
    }
  }
  const sample = DZ_FAMOUS.slice(0, 8)
  return `[DZ_FAMOUS_ALGERIANS]\n${sample.map(p => `• **${p.name}** — ${p.field} | ${p.from}`).join('\n')}\n[/DZ_FAMOUS_ALGERIANS]`
}
