export function getLawContext(msg) {
  const sections = []
  if (/طلاق|زواج|أسرة|إرث|ميراث|حضانة|نفقة|خلع/i.test(msg)) {
    const f = DZ_LAW.family
    if (/زواج/i.test(msg)) sections.push(`**قانون الزواج الجزائري**:\n• السن الأدنى: ${f.marriage.min_age}\n• الولي: ${f.marriage.wali}\n• عقد: ${f.marriage.contract}`)
    if (/طلاق|خلع/i.test(msg)) sections.push(`**أنواع الطلاق**: ${f.divorce.types.join(' | ')}\nالحضانة: ${f.divorce.custody}`)
    if (/إرث|ميراث/i.test(msg)) sections.push(`**قانون الإرث**:\n${f.inheritance.rules.join('\n')}`)
  }
  if (/عمل|عقد.*عمل|أجر|CNAS|CASNOS|تقاعد|فصل|بطالة/i.test(msg)) {
    const l = DZ_LAW.labor
    sections.push(`**قانون العمل الجزائري**:\n• ساعات العمل: ${l.working_hours}\n• الراتب الأدنى: ${l.min_wage}\n• الإجازة: ${l.annual_leave}\n• الفصل: إشعار ${l.firing.notice}`)
  }
  if (/شركة|CNRC|ضريبة|TVA|تجارة|EURL|SARL|SPA/i.test(msg)) {
    const c = DZ_LAW.commercial
    sections.push(`**القانون التجاري**:\n${Object.entries(c.company_types).map(([t,d]) => `• **${t}**: ${d}`).join('\n')}`)
  }
  if (/جواز|بطاقة وطنية|رخصة|سكن|AADL|ANSEJ|ANEM/i.test(msg)) {
    const a = DZ_LAW.administrative
    if (/جواز/i.test(msg)) sections.push(`**جواز السفر**: صلاحية ${a.passport.validity} | تكلفة ${a.passport.cost} | موقع: ${a.passport.online}`)
    if (/سكن|AADL/i.test(msg)) sections.push(`**برامج السكن والدعم الاجتماعي**:\n${Object.entries(a.social_programs).map(([k,v]) => `• **${k}**: ${v}`).join('\n')}`)
    if (/ANSEJ|شباب.*مشروع|تمويل/i.test(msg)) sections.push(`**دعم الشباب**: ANSEJ — ${a.social_programs.ANSEJ}`)
  }
  if (sections.length === 0) {
    sections.push(`**القانون الجزائري — نظرة سريعة**:\n• قانون الأسرة: نظام مختلط (شريعة إسلامية + قانون وضعي)\n• قانون العمل: حماية قوية للعمال (شهادة 90-11)\n• القانون التجاري: نظام LMD للشركات\n• الإجراءات الإدارية: متاحة إلكترونياً جزئياً`)
  }
  return `[DZ_LAW]\n${sections.join('\n\n')}\n[/DZ_LAW]`
}
