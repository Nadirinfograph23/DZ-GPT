export function isMusicArtsQuery(msg) {
  return /موسيقى|فن|سينما|راي|شعبي|قبائلي|أندلسي|مغني|مطرب|فنان|أغنية|أغاني|مسرح|سينما جزائرية|روائي|روايات جزائرية|أدب جزائري|خالد.*مطرب|إيدير|لونيس|فرقة|راي جزائري|هيب هوب|راب جزائري/i.test(msg)
}

export function getMusicArtsContext(msg) {
  const clean = msg.toLowerCase()
  const sections = []

  // موسيقى
  for (const [genre, info] of Object.entries(DZ_MUSIC_GENRES)) {
    if (clean.includes(genre.toLowerCase().split(' ')[0])) {
      sections.push(`**${genre}**: ${info.desc}\nأبرز الفنانين: ${info.stars?.slice(0,5).join(' · ')}`)
    }
  }

  // سينما وأدب
  if (/سينما|فيلم|مخرج/i.test(msg)) {
    sections.push(`**السينما الجزائرية**: ${DZ_ARTS_AND_CINEMA.cinema.desc}\nأبرز المخرجين: ${DZ_ARTS_AND_CINEMA.cinema.directors.join(' · ')}`)
  }
  if (/رواية|أدب|كاتب|روائي/i.test(msg)) {
    sections.push(`**الأدب الجزائري**:\nبالعربية: ${DZ_ARTS_AND_CINEMA.literature.arabicWriters.join(' · ')}\nبالفرنسية: ${DZ_ARTS_AND_CINEMA.literature.frenchWriters.join(' · ')}`)
  }

  if (sections.length === 0) {
    // نظرة عامة
    const genres = Object.keys(DZ_MUSIC_GENRES).slice(0, 4)
    sections.push(`الجزائر تزخر بتنوع موسيقي استثنائي:\n${genres.map(g => `• **${g}**: ${DZ_MUSIC_GENRES[g].origins}`).join('\n')}`)
  }

  return `[DZ_MUSIC_ARTS]\n${sections.join('\n\n')}\n[/DZ_MUSIC_ARTS]`
}
