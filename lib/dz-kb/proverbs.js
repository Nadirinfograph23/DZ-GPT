export function isProverbsQuery(msg) {
  return /مثل|أمثال|حكمة|حكم جزائر|قولة|قولوا|كما قال|كيما قالوا|مثلما يقولوا|مثال جزائري|أمثال دارجة|أمثل شعبي/i.test(msg)
}

export function getProverbsContext(msg) {
  const clean = msg.toLowerCase()
  // كشف الموضوع من الرسالة
  const tagMap = {
    'عائلة|أسرة|والدين|أم|أب|أخ': 'عائلة',
    'صبر|تصبر|اصبر': 'صبر',
    'عمل|شغل|كسب|رزق': 'عمل',
    'صداقة|صاحب|خو|صحاب': 'صداقة',
    'مال|فلوس|ثروة|غني|فقير': 'مال',
    'علم|تعليم|دراسة|مدرسة': 'تعليم',
    'كلام|لسان|حديث': 'كلام',
    'غربة|سفر|بلاد': 'غربة',
    'شجاعة|رجولة|كرم|ضيافة': 'كرم',
    'تواضع|كبر|غرور': 'تواضع',
  }
  let filtered = DZ_PROVERBS
  for (const [pattern, tag] of Object.entries(tagMap)) {
    if (new RegExp(pattern, 'i').test(clean)) {
      const byTag = DZ_PROVERBS.filter(p => p.tags.includes(tag))
      if (byTag.length >= 3) { filtered = byTag; break }
    }
  }
  const sample = filtered.slice(0, 12)
  const lines = sample.map(p => `• **"${p.text}"**\n  📍 ${p.region} | المعنى: ${p.meaning}`).join('\n')
  return `[DZ_PROVERBS — أمثال جزائرية]\n${lines}\n[/DZ_PROVERBS]`
}
