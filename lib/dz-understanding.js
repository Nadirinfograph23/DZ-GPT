function extractQuestionWord(msg) {
  const lower = msg.toLowerCase().trim()
  // فحص من الأطول للأقصر لضمان أفضل تطابق
  const sortedWords = Object.entries(DZ_QUESTION_WORDS)
    .sort((a, b) => b[0].length - a[0].length)
  for (const [word, info] of sortedWords) {
    const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    if (new RegExp(`(^|\\s)${escaped}(\\s|؟|\\?|$)`, 'i').test(lower)) {
      return { word, ...info }
    }
  }
  // كلمات الاستفهام الفصيحة
  const fusha = [
    { re: /^كيف\b/, word: 'كيف', type: 'how', format: 'خطوات مرقّمة' },
    { re: /^لماذا\b/, word: 'لماذا', type: 'why', format: 'السبب والعلة' },
    { re: /^ماذا\b/, word: 'ماذا', type: 'what', format: 'تعريف أو شرح' },
    { re: /^أين\b/, word: 'أين', type: 'where', format: 'مكان أو مصدر' },
    { re: /^من\b/, word: 'من', type: 'who', format: 'شخص أو جهة' },
    { re: /^متى\b/, word: 'متى', type: 'when', format: 'وقت أو تاريخ' },
    { re: /^ما\s+(هو|هي|هما)\b/, word: 'ما هو', type: 'what_is', format: 'تعريف واضح' },
    { re: /^ما\b/, word: 'ما', type: 'what', format: 'تعريف أو شرح' },
    { re: /^هل\b/, word: 'هل', type: 'yes_no', format: 'نعم أو لا مع سبب' },
    // فرنسية
    { re: /^comment\b/i, word: 'comment', type: 'how', format: 'étapes' },
    { re: /^pourquoi\b/i, word: 'pourquoi', type: 'why', format: 'raison' },
    { re: /^où\b/i, word: 'où', type: 'where', format: 'lieu ou lien' },
    { re: /^qui\b/i, word: 'qui', type: 'who', format: 'personne ou entité' },
    { re: /^quand\b/i, word: 'quand', type: 'when', format: 'date ou heure' },
    { re: /^combien\b/i, word: 'combien', type: 'how_much', format: 'quantité ou prix' },
    { re: /^qu(oi|'est.ce)\b/i, word: 'quoi', type: 'what', format: 'définition' },
  ]
  for (const f of fusha) {
    if (f.re.test(lower)) return { word: f.word, type: f.type, format: f.format }
  }
  return null
}

function detectImplicitNeed(msg) {
  for (const ip of IMPLICIT_NEEDS) {
    if (ip.re.test(msg)) return ip
  }
  return null
}

function detectAmbiguity(msg) {
  for (const am of AMBIGUITIES) {
    if (am.re.test(msg)) return am
  }
  return null
}

function detectTone(msg) {
  for (const tp of TONE_PATTERNS) {
    if (tp.re.test(msg)) return tp
  }
  return null
}

function detectTechLevel(msg) {
  for (const tp of TECH_PATTERNS) {
    if (tp.re.test(msg)) return tp
  }
  return null
}

function detectAlgerianContext(msg) {
  const found = []
  for (const p of ALGERIAN_CONTEXT_PATTERNS) {
    if (p.re.test(msg)) found.push(p.ctx)
  }
  return found
}

function hasDarijaContent(msg) {
  return /واش|كيفاش|علاش|علاه|فين|وين|شكون|شحال|قداه|بكام|فوقاش|وقتاش|بزاف|مليح|خايب|مليح|يلا|درك|دروك|ضرك|برك|بصح|خلاص|معليش|ماشي|راني|راك|راه|تنجم|نجم|يخمم|كلش|قاع|هادا|هادي|زعفان|فرحان|تاني|ديجا|واه|هيه|صاح|ياسر|وايلو|مخربق|مهبول|يسقسي/.test(msg)
}

