/**
 * buildUnderstandingContext(msg, opts)
 *
 * يبني كتلة system-prompt تحتوي على تحليل عميق للسؤال.
 * تُضاف إلى system prompt قبل استدعاء AI.
 *
 * @param {string} msg  - رسالة المستخدم
 * @param {Object} opts
 * @param {boolean} opts.isOwnerAnswer   - حذف إذا كان الرد من المالك (static fact)
 * @param {boolean} opts.isStaticAnswer  - حذف إذا كان رداً محفوظاً
 * @param {boolean} opts.includeDzFeed   - إضافة التغذية اللغوية الكاملة (افتراضي: تلقائي)
 * @returns {string|null} - كتلة system prompt أو null إذا لم يكن هناك محتوى
 */
export function buildUnderstandingContext(msg, opts = {}) {
  if (!msg || msg.trim().length < 2) return null

  // تجاوز كامل إذا كان الرد محدداً مسبقاً
  if (opts.isOwnerAnswer || opts.isStaticAnswer) return null

  const lines = []
  const isDarija = hasDarijaContent(msg)
  let hasContent = false

  // ① نوع سؤال الدارجة
  const qWord = extractQuestionWord(msg)
  if (qWord) {
    const typeLabel = {
      what_or_yn: 'نعم/لا أو تعريف',
      how: 'طريقة + خطوات',
      how_to: 'خطوات تدريجية',
      how_works: 'شرح الآلية',
      why: 'السبب والعلة',
      where: 'مكان أو مصدر',
      who: 'شخص أو جهة',
      when: 'وقت أو تاريخ',
      how_much: 'كمية أو سعر',
      price: 'سعر + مصدر + تاريخ',
      which: 'مقارنة + توصية',
      exists: 'موجود/غير موجود + بديل',
      state: 'وصف الحالة',
      yes_no: 'إجابة مباشرة نعم/لا',
      from_where: 'مصدر أو منشأ',
      find: 'رابط أو مكان',
    }[qWord.type] || qWord.format
    lines.push(`🎯 نوع السؤال: "${qWord.word}" → ${typeLabel}`)
    hasContent = true
  }

  // ② الحاجة الضمنية
  const implicitNeed = detectImplicitNeed(msg)
  if (implicitNeed) {
    lines.push(`💭 الحاجة الضمنية: ${implicitNeed.hint}`)
    hasContent = true
  }

  // ③ الغموض المحتمل
  const ambiguity = detectAmbiguity(msg)
  if (ambiguity) {
    lines.push(`⚠️ غموض: قد يقصد أحد هذه: [${ambiguity.candidates.join(' / ')}] — ${ambiguity.hint}`)
    hasContent = true
  }

  // ④ الحالة العاطفية
  const tone = detectTone(msg)
  if (tone) {
    lines.push(`🎭 نبرة المستخدم: ${tone.tone} — ${tone.adapt}`)
    hasContent = true
  }

  // ⑤ المستوى التقني
  const techLevel = detectTechLevel(msg)
  if (techLevel) {
    lines.push(`🔧 المستوى التقني: ${techLevel.level} — ${techLevel.hint}`)
    hasContent = true
  }

  // ⑥ السياق الجزائري
  const algCtx = detectAlgerianContext(msg)
  if (algCtx.length > 0) {
    lines.push(`🇩🇿 السياق الجزائري: ${algCtx.join('، ')}`)
    hasContent = true
  }

  // ⑦ هل الرسالة بالدارجة؟
  if (isDarija) {
    lines.push(`🗣️ لغة المستخدم: دارجة جزائرية — أجب بالدارجة الجزائرية بشكل طبيعي.`)
    hasContent = true
  }

  if (!hasContent) return null

  // تجميع الكتلة
  const block = [
    '━━━ عقل الفهم — DZ Understanding Brain ━━━',
    ...lines,
    '✅ فهم هذا التحليل قبل الإجابة — لا تُظهر هذا التحليل للمستخدم.',
  ].join('\n')

  // ⑧ تغذية لغوية بالدارجة (أضفها إذا كان السؤال بالدارجة أو طُلب ذلك)
  const includeFeed = opts.includeDzFeed !== false && isDarija
  if (includeFeed) {
    return block + '\n\n' + DZ_LANGUAGE_FEED
  }

  return block
}

/**
 * isDarijaMessage(msg) — للاستخدام الخارجي
 * يرجع true إذا كانت الرسالة تحتوي على دارجة جزائرية
 */
export function isDarijaMessage(msg) {
  return hasDarijaContent(msg)
}

export default { buildUnderstandingContext, isDarijaMessage }
