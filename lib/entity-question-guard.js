/**
 * lib/entity-question-guard.js  v1.0
 * ════════════════════════════════════════════════════════════════════════════
 * Entity Question Guard — طبقة الكشف المبكر لأسئلة تعريف الكيانات
 *
 * القاعدة الذهبية:
 *  "من هو / من هي / ما هو + منصب/كيان" → Knowledge Agent
 *  حتى لو احتوى: الحالي / الجديد / السابق / الآن
 *
 * هذه الطبقة تعمل قبل أي فحص خبري أو زمني.
 * Exports:
 *   isEntityDefinitionQuery(q)  → boolean  (سؤال تعريف كيان → لا تُرسله للبحث الحي)
 *   isExplicitNewsQuery(q)      → boolean  (سؤال أخبار صريح → أرسله للبحث الحي)
 * ════════════════════════════════════════════════════════════════════════════
 */

// ── أنماط أسئلة تعريف الكيان (WHO / WHAT + Role) ─────────────────────────────
// تُطابق أسئلة "من هو رئيس X الحالي/السابق/الجديد" بغض النظر عن الصفة الزمنية
const ENTITY_DEFINITION_PATTERNS = [
  // ① من هو / من هي + منصب أو اسم (حتى مع الحالي/السابق/الجديد)
  /^(?:من\s+(?:هو|هي)|شكون\s+(?:هو|هي))\s+.{2,}/i,

  // ② ما هو / ما هي + كيان
  /^(?:ما\s+(?:هو|هي|هم))\s+.{2,}/i,

  // ③ الرئيس/الوزير/الملك/الحاكم + (الدولة|الوصف) + (الحالي|السابق|الجديد)؟
  /(?:رئيس|وزير|ملك|أمير|حاكم|والي|مدير|وزيرة|رئيسة)\s+.{2,50}?(?:الحالي|الحالية|السابق|السابقة|الجديد|الجديدة|الحاضر)?(?:\s*[؟?])?$/i,

  // ④ "الرئيس الأمريكي/الفرنسي/..." الحالي
  /(?:الرئيس|رئيس\s+الجمهورية)\s+(?:الأمريكي|الفرنسي|المصري|الجزائري|الإيراني|التركي|الروسي|الصيني|البريطاني|الألماني|الإيطالي|الإسباني|البرازيلي|الأردني|السعودي|المغربي|التونسي|اللبناني|العراقي|الإماراتي|القطري|الكويتي)/i,

  // ⑤ من يشغل / من يتولى منصب
  /(?:من\s+يشغل|من\s+يتولى|من\s+يحمل)\s+(?:منصب|حقيبة|وظيفة)\s+/i,

  // ⑥ وزير الداخلية/الخارجية/... + (أي دولة)؟ → طلب تعريف
  /^(?:من\s+هو\s+)?(?:وزير|وزيرة)\s+(?:الداخلية|الخارجية|الدفاع|التعليم|الصحة|المالية|العدل|الطاقة|الزراعة|النقل|السياحة|الثقافة|الاتصال|التجارة|الصناعة|الشباب|الدين|الأوقاف)/i,

  // ⑦ والي + ولاية X
  /^(?:من\s+هو\s+)?والي\s+(?:ولاية\s+)?.{2,30}(?:الحالي|الجديد)?\s*[؟?]?$/i,

  // ⑧ رئيس الحكومة / الوزير الأول + (الدولة) → طلب تعريف
  /^(?:من\s+هو\s+)?(?:رئيس\s+الحكومة|الوزير\s+الأول|رئيس\s+الوزراء)\s*/i,

  // ⑨ who is + position (English)
  /^who\s+is\s+(?:the\s+)?(?:current\s+|new\s+|former\s+)?(?:president|minister|king|prime minister|governor|chancellor|secretary)/i,

  // ⑩ qui est + poste (French)
  /^qui\s+est\s+(?:le\s+|la\s+|l[''])?(?:président|ministre|roi|premier ministre)/i,
]

// ── أنماط الأخبار الصريحة — هذه فقط تذهب للبحث الحي ─────────────────────────
// تُطابق أسئلة "آخر أخبار / ماذا صرح / أين التقى / آخر تصريح"
const EXPLICIT_NEWS_PATTERNS = [
  // آخر أخبار X / مستجدات X
  /(?:آخر|أحدث|أخير)\s+(?:أخبار|خبر|مستجدات|تطورات|تصريح|تصريحات|لقاء|زيارة|اجتماع|حديث)/i,
  /(?:مستجدات|تطورات|جديد)\s+(?:عن|حول|بخصوص|ل[ـ]?)\s+\S+/i,

  // ماذا صرح / قال / أعلن اليوم
  /(?:ماذا|وش|واش)\s+(?:صرّح|قال|أعلن|صرح)\s+/i,

  // أين التقى / أين كان الرئيس هذا الأسبوع
  /(?:أين|وين)\s+(?:التقى|كان|سيكون|يوجد)\s+.{2,}\s+(?:اليوم|الأسبوع|هذا\s+الأسبوع|الليلة|أمس)/i,

  // آخر زيارة / آخر لقاء للرئيس
  /(?:آخر|أخير|أحدث)\s+(?:زيارة|لقاء|اجتماع|مؤتمر|خطاب)\s+(?:لـ?|لل|ل)\s*/i,

  // what did X say today / latest statement
  /(?:latest\s+(?:news|statement|speech)|what\s+did\s+\S+\s+(?:say|announce|declare))/i,

  // عاجل: / breaking:
  /(?:عاجل|عاجلاً|breaking)\s*[:؟?]/i,

  // أخبار اليوم عن X
  /أخبار\s+(?:اليوم|هذا\s+الأسبوع)\s+(?:عن|حول|بخصوص)/i,
]

// ── كلمات مؤقتة لا تُلغي سؤال التعريف ──────────────────────────────────────────
// "الحالي / السابق / الجديد / الحاضر / المعيَّن حديثاً" جزء من التعريف وليست طلب أخبار
const ENTITY_TEMPORAL_ADJECTIVES = [
  /\bالحالي\b/i, /\bالحالية\b/i,
  /\bالسابق\b/i, /\bالسابقة\b/i,
  /\bالجديد\b/i, /\bالجديدة\b/i,
  /\bالحاضر\b/i, /\bالحاضرة\b/i,
  /\bالمعين\b/i, /\bالمعيّن\b/i,
  /\bcurrent\b/i, /\bformer\b/i, /\bnew\b/i,
]

/**
 * isEntityDefinitionQuery(q)
 * هل السؤال يطلب تعريف/هوية كيان؟
 * → true: ابعثه للـ Knowledge Agent حتى لو احتوى "الحالي/اليوم/..."
 * → false: اترك الـ pipeline العادي يقرر
 *
 * @param {string} q - استعلام المستخدم
 * @returns {boolean}
 */
export function isEntityDefinitionQuery(q = '') {
  if (!q || q.length < 4) return false
  const qTrim = q.trim()

  // أولاً: إذا كان سؤال أخبار صريح → ليس تعريفاً (حتى لو بدأ بـ "من هو")
  if (EXPLICIT_NEWS_PATTERNS.some(p => p.test(qTrim))) return false

  // ثانياً: إذا طابق أنماط تعريف الكيان → هو تعريف
  if (ENTITY_DEFINITION_PATTERNS.some(p => p.test(qTrim))) return true

  return false
}

/**
 * isExplicitNewsQuery(q)
 * هل السؤال يطلب أخباراً أو أحداثاً حية بشكل صريح؟
 * → true: أرسله للـ Search/News Agent
 *
 * @param {string} q
 * @returns {boolean}
 */
export function isExplicitNewsQuery(q = '') {
  if (!q || q.length < 4) return false
  return EXPLICIT_NEWS_PATTERNS.some(p => p.test(q.trim()))
}

/**
 * getEntityQueryType(q)
 * يُعيد نوع السؤال للـ logging والـ debugging
 *
 * @param {string} q
 * @returns {'ENTITY_DEFINITION' | 'EXPLICIT_NEWS' | 'UNKNOWN'}
 */
export function getEntityQueryType(q = '') {
  if (isExplicitNewsQuery(q)) return 'EXPLICIT_NEWS'
  if (isEntityDefinitionQuery(q)) return 'ENTITY_DEFINITION'
  return 'UNKNOWN'
}
