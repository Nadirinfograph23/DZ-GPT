  lines.push(`| المرحلة | الموعد |`)
  lines.push(`|---------|--------|`)
  lines.push(`| دور المجموعات | 11 – 26 يونيو 2026 |`)
  lines.push(`| دور الـ32 | 29 يونيو – 3 يوليو 2026 |`)
  lines.push(`| ربع النهائي | 7 – 9 يوليو 2026 |`)
  lines.push(`| نصف النهائي | 12 – 14 يوليو 2026 |`)
